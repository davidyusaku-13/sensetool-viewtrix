"""Helpers shared by the C code generators (prjset, appset, scanarr) and the
spreadsheet readers."""
import re
import textwrap

IDENT_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def is_identifier(name):
    """A valid C identifier (also used for macro, enum and field names)."""
    return bool(name) and bool(IDENT_RE.match(name))


def cell_text(v):
    """A spreadsheet cell or YAML value as clean text: None -> "", 3.0 -> "3"."""
    if v is None:
        return ""
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    return str(v).replace("\t", " ").strip()


def _safe(text):
    return (text or "").replace("*/", "* /")


def line_comment(text):
    """One-line comment, or "" for empty text. Text cannot close the comment early."""
    t = " ".join(_safe(text).split())
    return f"/* {t} */" if t else ""


def block_comment(text):
    """Comment lines for multi-line text: one line stays a one-line comment."""
    lines = [ln.strip() for ln in _safe(text).splitlines() if ln.strip()]
    if not lines:
        return []
    if len(lines) == 1:
        return [f"/* {lines[0]} */"]
    return ["/*"] + [f" * {ln}" for ln in lines] + [" */"]


def banner(filename, what, edit_where):
    """File header of a generated file, e.g. banner("appset.h", "Application Setting",
    "application setting in SenseTool")."""
    note = f"Generated by SenseTool. Do not edit by hand; edit the {edit_where} and regenerate instead."
    return ["/*", f" * {filename} - {what}"] + [f" * {ln}" for ln in textwrap.wrap(note, 66)] + [" */"]
