"""prjcfg.yaml: one YAML file holding everything prjcfg.xlsx used to hold.

The file has a section per workspace, each in the same format as that
workspace's own export:

    prjset:  {title, desc, data: [...]}                 Project Setting   -> prjset.h
    appset:  {title, desc, size, registers: [...]}      App Setting       -> appset.c/.h
    scanarr: {title, desc, scan_items, arrangements}    Scan Arrangement  -> afeScanArrg.c/.h

Every workspace's Import accepts either its own file or this combined one.

Convert an updated spreadsheet with:
    uv run python -m src.modules.prjcfg prjcfg.xlsx yaml/prjcfg.yaml
"""
import re
import sys
import yaml
from . import appset, prjset, scanarr

PRJSET_DESC = ("Project Setting includes the static information which is not be changed during runtime. "
               "This parameter should be set during the project development phase and fixed after project deployment. "
               "A file prjset.h shall be generated by script.")
APPSET_DESC = ("Application Setting includes the dynamic settings which can be changed during runtime. "
               "appset.h and appset.c are generated from this file.")
SCANARR_DESC = ("Scan items are the eAfeScanID_t enum in value order (the first is 0). "
                "afeScanArrg.c and afeScanArrg.h are generated from this file.")
DESC = ("Project configuration for the FW: Project Setting, Application Setting and Scan Arrangement. "
        "Replaces prjcfg.xlsx; edit it in SenseTool, which generates the C code.")


def section(data, key):
    """The `key` section of a combined prjcfg.yaml, or `data` itself for a single-workspace file."""
    if isinstance(data, dict) and isinstance(data.get(key), dict):
        return data[key]
    return data


# ---- documents (shared by the workspace exports and the converter) ---------
def _num(v):
    """Plain decimal text as a YAML number, anything else (hex, expressions) as text."""
    v = "" if v is None else str(v)
    return int(v) if re.fullmatch(r"-?\d+", v.strip()) else (v or None)


def prjset_doc(items):
    """items: [{name, value, desc, group, comment}]"""
    data = []
    for i in items:
        d = {k: (str(i.get(k) or "") or None) for k in ("name", "value", "desc", "group", "comment")}
        d["value"] = _num(d["value"])
        data.append(d)
    return {"title": "Project Settings", "desc": PRJSET_DESC, "data": data}


def appset_doc(regs):
    """regs: [{addr, name, size, category, desc, fields: [{name, msb, lsb, default}]}]"""
    out = []
    for r in regs:
        out.append({
            "addr": _num(r["addr"]), "name": r["name"], "size": _num(r["size"]),
            "category": r["category"] or None, "desc": r["desc"] or None,
            # defaults stay text so hex stays hex
            "fields": [{"name": f["name"], "msb": _num(f["msb"]), "lsb": _num(f["lsb"]),
                        "default": f["default"] or None} for f in r["fields"]],
        })
    return {"title": "Application Settings", "desc": APPSET_DESC, "size": appset.APPSET_SIZE,
            "registers": out}


def scanarr_doc(items, arrs):
    """items: [{name, desc}] in enum order, arrs: [{id, name, desc, scans}]"""
    def arr_id(v):
        n = scanarr.parse_id(v)
        return n if n is not None else v
    return {
        "title": "Scan Arrangement", "desc": SCANARR_DESC,
        "scan_items": [{"name": i["name"], "desc": i.get("desc") or None} for i in items],
        "arrangements": [{"id": arr_id(a["id"]), "name": a["name"], "desc": a.get("desc") or None,
                          "scans": list(a["scans"])} for a in arrs],
    }


def dump(data, f):
    yaml.dump(data, f, sort_keys=False, allow_unicode=True)


# ---- spreadsheet conversion ------------------------------------------------
def _revisions(path):
    import openpyxl
    wb = openpyxl.load_workbook(path, read_only=True)
    out = []
    if "ReadMe" in wb.sheetnames:
        for row in wb["ReadMe"].iter_rows(values_only=True):
            date, text = (list(row) + [None, None])[:2]
            if hasattr(date, "strftime") and text:
                out.append({"date": date.strftime("%Y-%m-%d"), "desc": str(text).strip()})
    wb.close()
    return out


def from_xlsx(path):
    """Convert all three data sheets of prjcfg.xlsx into one combined document."""
    regs = [appset_clean(r) for r in appset.read_appset_xlsx(path)]
    regs.sort(key=lambda r: appset.to_int(r["addr"]) if appset.to_int(r["addr"]) is not None else 1 << 30)
    scan = scanarr.read_scanarrg_xlsx(path)
    doc = {"title": "Project Configuration", "desc": DESC}
    revisions = _revisions(path)
    if revisions:
        doc["revisions"] = revisions
    doc["prjset"] = prjset_doc(prjset.read_prjcfg_xlsx(path))
    doc["appset"] = appset_doc(regs)
    doc["scanarr"] = scanarr_doc(scan["scan_items"], scan["arrangements"])
    return doc, scan["skipped"]


def appset_clean(reg):
    """Normalise a register coming from QML or a file: every value is text."""
    s = appset._s
    return {
        "addr": s(reg.get("addr")),
        "name": s(reg.get("name")),
        "size": s(reg.get("size")) or "1",
        "category": s(reg.get("category")),
        "desc": s(reg.get("desc")),
        "fields": [{"name": s(f.get("name")), "msb": s(f.get("msb")), "lsb": s(f.get("lsb")),
                    "default": s(f.get("default"))} for f in (reg.get("fields") or [])],
    }


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 2:
        print("usage: python -m src.modules.prjcfg <prjcfg.xlsx> <out.yaml>", file=sys.stderr)
        return 2
    doc, skipped = from_xlsx(argv[0])
    with open(argv[1], "w", encoding="utf-8", newline="\n") as f:
        dump(doc, f)
    print(f"{argv[1]}: {len(doc['prjset']['data'])} project settings, "
          f"{len(doc['appset']['registers'])} app registers, "
          f"{len(doc['scanarr']['scan_items'])} scan items, "
          f"{len(doc['scanarr']['arrangements'])} arrangements")
    for s in skipped:
        print(f"  skipped ScanArrg row: {s}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
