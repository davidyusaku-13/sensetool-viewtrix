import unittest
from src.modules import cgen


class CGenTestCase(unittest.TestCase):
    def test_identifiers(self):
        self.assertTrue(cgen.is_identifier("AFE_END"))
        self.assertTrue(cgen.is_identifier("_x1"))
        self.assertFalse(cgen.is_identifier("9X"))
        self.assertFalse(cgen.is_identifier(""))
        self.assertFalse(cgen.is_identifier(None))

    def test_cell_text(self):
        self.assertEqual(cgen.cell_text(None), "")
        self.assertEqual(cgen.cell_text(3.0), "3")
        self.assertEqual(cgen.cell_text(2.5), "2.5")
        self.assertEqual(cgen.cell_text("  a\tb "), "a b")

    def test_comments_cannot_be_closed_early(self):
        self.assertEqual(cgen.line_comment("a */ b\n c"), "/* a * / b c */")
        self.assertEqual(cgen.line_comment("  "), "")
        self.assertEqual(cgen.block_comment("one"), ["/* one */"])
        self.assertEqual(cgen.block_comment("one\ntwo */"), ["/*", " * one", " * two * /", " */"])
        self.assertEqual(cgen.block_comment(""), [])

    def test_banner(self):
        self.assertEqual(cgen.banner("afeScanArrg.h", "Scan Arrangement", "scan arrangement in SenseTool"), [
            "/*",
            " * afeScanArrg.h - Scan Arrangement",
            " * Generated by SenseTool. Do not edit by hand; edit the scan",
            " * arrangement in SenseTool and regenerate instead.",
            " */",
        ])


if __name__ == "__main__":
    unittest.main()
